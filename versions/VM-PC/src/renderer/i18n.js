let currentLanguage = localStorage.getItem('appLanguage') || 'ar';

function t(key) {
  return translations[currentLanguage]?.[key] || translations.ar[key] || key;
}

function getLanguage() {
  return currentLanguage;
}

function getLanguageDir(lang = currentLanguage) {
  return lang === 'ar' ? 'rtl' : 'ltr';
}

function setLanguage(lang) {
  if (!translations[lang]) {
    return;
  }

  currentLanguage = lang;
  localStorage.setItem('appLanguage', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = getLanguageDir(lang);
  document.title = t('appTitle');
  applyTranslations();

  if (window.electronAPI?.setLanguage) {
    window.electronAPI.setLanguage(lang);
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    if (el.dataset.i18nDynamic === 'true') {
      return;
    }

    const key = el.dataset.i18n;
    if (key) {
      el.textContent = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.alt = t(el.dataset.i18nAlt);
  });

  const langSelect = document.getElementById('languageSelect');
  if (langSelect) {
    langSelect.value = currentLanguage;
  }

  if (typeof window.onLanguageChanged === 'function') {
    window.onLanguageChanged(currentLanguage);
  }
}

window.i18n = { t, setLanguage, getLanguage, getLanguageDir, applyTranslations, translations };
